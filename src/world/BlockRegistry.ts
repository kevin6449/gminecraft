export type ToolCategory = 'pickaxe' | 'axe' | 'shovel' | 'sword' | 'none';

export interface ItemDef {
  id: BlockId;
  name: string;
  isBlock: boolean;
  hardness: number; // 徒手挖掘秒數 (-1 代表不可破壞)
  materialAttr?: string; // 方塊材質屬性描述
  preferredTool: ToolCategory;
  toolType?: ToolCategory;
  toolMultiplier?: number;
  attackDamage?: number;
  foodRestore?: number;
  transparent?: boolean;
  fluid?: boolean;
  solid?: boolean;
  isDoor?: boolean;
  isDoorOpen?: boolean;
  isDoorTop?: boolean;
  lightEmission?: number; // 0 ~ 1
  dropId?: BlockId;
  textures: {
    top: number;
    bottom: number;
    side: number;
  };
  mapColor: string;
  soundType: 'grass' | 'stone' | 'wood' | 'sand' | 'glass' | 'water';
}

